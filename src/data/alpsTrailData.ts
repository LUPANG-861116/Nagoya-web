  const waypointsXML = ALPS_WAYPOINTS.map((w) => `  <wpt lat="${w.lat}" lon="${w.lng}">
    <ele>${w.elevation}</ele>
    <name>${w.name}</name>
    <desc>${w.desc}${w.tips ? ' (' + w.tips + ')' : ''}</desc>
  </wpt>`).join('\n');

  const trackPointsXML = DENSE_TRAIL_POINTS.map(([lat, lng, ele]) => `      <trkpt lat="${lat}" lon="${lng}">
        <ele>${ele}</ele>
      </trkpt>`).join('\n');

